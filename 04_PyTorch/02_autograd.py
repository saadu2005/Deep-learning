# ==========================================
# 1. Import Libraries
# ==========================================
import torch

# ==========================================
# 2. Create Variable
# ==========================================
x = torch.tensor(3.0, requires_grad=True)

# ==========================================
# 3. Create Function
# ==========================================
y = x ** 2

# ==========================================
# 4. Calculate Gradient
# ==========================================
y.backward()

# ==========================================
# 5. Display Result
# ==========================================
print("x:", x.item())
print("y:", y.item())
print("dy/dx:", x.grad.item())
