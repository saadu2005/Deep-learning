# ==========================================
# 1. Import Libraries
# ==========================================
import numpy as np

# ==========================================
# 2. Input Layer
# ==========================================
X = np.array([[1.0, 2.0]])

# ==========================================
# 3. Hidden Layer Parameters
# ==========================================
W1 = np.array([[0.5, 0.2], [0.3, 0.7]])
b1 = np.array([[0.1, 0.2]])

# ==========================================
# 4. Forward Propagation
# ==========================================
hidden = np.maximum(0, X @ W1 + b1)

# ==========================================
# 5. Output Layer
# ==========================================
W2 = np.array([[0.6], [0.4]])
b2 = np.array([[0.1]])
output = hidden @ W2 + b2

# ==========================================
# 6. Display Result
# ==========================================
print("Hidden Layer Output:", hidden)
print("Final Output:", output)
